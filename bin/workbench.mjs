#!/usr/bin/env node
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readJSON} from '../lib/io.mjs';
import {defaultData, checkoutRepository, openTask, prepare, repair, recordObservations, feedback, handoff, confirmCoverage} from '../lib/workbench.mjs';
import {audit,status} from '../lib/audit.mjs';
import {ensurePreview,stopPreview} from '../lib/preview.mjs';
import {learnTask,captureDialogue} from '../lib/experience.mjs';
import {ExperienceBridgeClient} from '../lib/experience-bridge.mjs';
import {inspectSource} from './intake.mjs';
import {experiencePage} from '../lib/site-rules.mjs';
export async function workbench(args) {
  const [action,...rest] = args, options = {};
  if (!action || ['help','--help'].includes(action)) return {
    workflow:'Git → audit → repair → designer feedback → scoped shared experience',
    commands:{checkout:'checkout --id ID --repo URL_OR_LOCAL_GIT [--ref BRANCH] (once; inspect source before choosing config)',start:'start --id ID --repo URL_OR_LOCAL_GIT --config task.json [--ref BRANCH]',open:'open (same inputs, register without building)',cycle:'cycle --id ID',status:'status --id ID',repair:'repair --id ID --file edits.json',observe:'observe --id ID --file observations.json',coverage:'coverage --id ID --file coverage.json',handoff:'handoff --id ID',feedback:'feedback --id ID --file designer-feedback.json',preview:'preview --id ID',stop:'stop-preview --id ID',learn:'learn --id ID --file lesson.json'},
    options:'All commands accept --data PATH. Set SITE_BROWSER_EXECUTABLE to an available Chromium. DA_EXPERIENCE_URL and DA_EXPERIENCE_TOKEN connect the shared service. Visual judgments and human approval are never generated by the automatic scanner.'};
  for (let i=0;i<rest.length;i+=2) { if (!rest[i].startsWith('--') || rest[i+1] === undefined) throw Error('Expected --key value'); options[rest[i].slice(2)] = rest[i+1]; }
  const data = path.resolve(options.data || defaultData), id = options.id, client = new ExperienceBridgeClient({data,url:options['experience-url'] || process.env.DA_EXPERIENCE_URL,token:process.env.DA_EXPERIENCE_TOKEN});
  try {
    if(action==='inspect')return inspectSource(path.resolve(options.source));
    if (action === 'checkout') return checkoutRepository({data,id,repo:options.repo,ref:options.ref});
    const payload = options.file ? await readJSON(path.resolve(options.file)) : {};
    if (action === 'open' || action === 'start') {
      let config = await readJSON(path.resolve(options.config));
      const checkout=await checkoutRepository({data,id,repo:options.repo,ref:options.ref});
      if(!config.siteType){const detected=await inspectSource(checkout.source);if(detected.siteType)config={...config,siteType:detected.siteType};}
      const lessons = await client.search({pages:[...new Set(config.pages.map(p=>experiencePage(config.siteType,p.family)))],site:options.repo});
      await openTask({data,id,repo:options.repo,ref:options.ref,config,lessons:lessons.cases});
      if (action === 'open') return {id,step:'registered',experience:lessons.source || 'local'};
      await prepare(data,id); await audit({data,id}); return status(data,id);
    }
    if (action === 'cycle') { await prepare(data,id); await audit({data,id}); return status(data,id); }
    if (action === 'status') return status(data,id,options.detail);
    if (action === 'repair') { await repair({...payload,data,id}); await audit({data,id}); return status(data,id); }
    if (action === 'observe') { await recordObservations({...payload,data,id}); return status(data,id); }
    if (action === 'coverage') { await confirmCoverage({...payload,data,id}); return status(data,id); }
    if (action === 'feedback') {
      await feedback({...payload,data,id});
      const experience = await captureDialogue({data,id,client}), records = experience.records || [experience];
      return {...await status(data,id),experienceSync:experience.sync,experience:{shared:records.length > 0 && records.every(r=>r.shared === true && r.sync !== 'queued'),records:records.map(r=>({id:r.id,status:r.status,sync:r.sync,shared:r.shared,lessons:r.lessons,review:r.review,conflicts:r.conflicts}))}};
    }
    if (action === 'handoff') { await handoff(data,id); return {task:await status(data,id),preview:await ensurePreview(data,id)}; }
    if (action === 'preview') return ensurePreview(data,id);
    if (action === 'stop-preview') { await stopPreview(data,id); return {id,stopped:true}; }
    if (action === 'learn') return learnTask({...payload,data,id,client});
    throw Error('Unknown workbench command');
  } finally { await client.close(); }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(JSON.stringify(await workbench(process.argv.slice(2)),null,2)); }
  catch (error) { console.error(error.message); process.exitCode=1; }
}
