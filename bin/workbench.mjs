#!/usr/bin/env node
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readJSON} from '../lib/io.mjs';
import {defaultData, checkoutRepository, openTask, prepare, repair, prepareAdjustment, resumeAcceptance, loadTask, recordObservations, feedback, handoff, confirmCoverage} from '../lib/workbench.mjs';
import {audit,status} from '../lib/audit.mjs';
import {ensurePreview,stopPreview} from '../lib/preview.mjs';
import {learnTask} from '../lib/experience.mjs';
import {scheduleFeedbackDelivery} from '../lib/feedback-delivery.mjs';
import {ExperienceBridgeClient} from '../lib/experience-bridge.mjs';
import {inspectSource} from './intake.mjs';
import {experiencePage} from '../lib/site-rules.mjs';
import {selectTaskExperience} from '../lib/experience-selection.mjs';
export async function workbench(args) {
  const [action,...rest] = args, options = {};
  if (!action || ['help','--help'].includes(action)) return {
    workflow:'New source: full acceptance. Designer adjustment: edit → immediate preview → scoped recheck → designer confirmation → background experience delivery.',
    commands:{checkout:'checkout --id ID (--repo URL_OR_LOCAL_GIT [--ref BRANCH] | --source LOCAL_DIRECTORY)',start:'start --id ID (--repo URL_OR_LOCAL_GIT [--ref BRANCH] | --source LOCAL_DIRECTORY) --config task.json [--mode acceptance|adjustment]',open:'open (same inputs, register without building)',cycle:'cycle --id ID [--mode acceptance|adjustment]',adjust:'adjust --id ID --file adjustment.json (edits optional; returns preview before testing)',recheck:'recheck --id ID (only current adjustment)',status:'status --id ID',repair:'repair --id ID --file edits.json (full checks during acceptance; preview during designer adjustment)',observe:'observe --id ID --file observations.json',coverage:'coverage --id ID --file coverage.json',handoff:'handoff --id ID',feedback:'feedback --id ID --file designer-feedback.json',preview:'preview --id ID',stop:'stop-preview --id ID',learn:'learn --id ID --file lesson.json'},
    options:'All commands accept --data PATH. Set SITE_BROWSER_EXECUTABLE to an available Chromium. DA_EXPERIENCE_URL and DA_EXPERIENCE_TOKEN connect the shared service. Visual judgments and human approval are never generated by the automatic scanner.'};
  for (let i=0;i<rest.length;i+=2) { if (!rest[i].startsWith('--') || rest[i+1] === undefined) throw Error('Expected --key value'); options[rest[i].slice(2)] = rest[i+1]; }
  const data = path.resolve(options.data || defaultData), id = options.id, client = new ExperienceBridgeClient({data,url:options['experience-url'] || process.env.DA_EXPERIENCE_URL,token:process.env.DA_EXPERIENCE_TOKEN});
  if(options.mode && !['acceptance','adjustment'].includes(options.mode))throw Error('Use --mode acceptance or adjustment');
  const adjustmentPreview = async payload => {
    await prepareAdjustment({...payload,data,id});
    return {task:await status(data,id),preview:await ensurePreview(data,id),next:'Show this candidate now. Then recheck the affected scope and record actual visual observations; this preview is not full-site acceptance.'};
  };
  try {
    if(action==='inspect')return inspectSource(path.resolve(options.source));
    if (action === 'checkout') return checkoutRepository({data,id,repo:options.repo,ref:options.ref,localSource:options.source});
    const payload = options.file ? await readJSON(path.resolve(options.file)) : {};
    if (action === 'open' || action === 'start') {
      let config = await readJSON(path.resolve(options.config));
      if(options.mode)config={...config,workflow:options.mode};
      const checkout=await checkoutRepository({data,id,repo:options.repo,ref:options.ref,localSource:options.source});
      const detected=await inspectSource(checkout.source);
      const declarations=[...new Set(detected.evidence.map(e=>e.declaredSiteType).filter(Boolean))];
      if(declarations.length>1 || (config.siteType && declarations.length===1 && declarations[0]!==config.siteType))
        throw Error('Site type conflicts with actual source declarations; inspect product and source before continuing');
      if(!config.siteType&&detected.classification==='declared-with-source-evidence')config={...config,siteType:detected.siteType};
      if(!config.siteType)throw Error('Site type is ambiguous; Agent must inspect the actual product and pages before selecting rules or experience');
      const lessons = await client.search({pages:[...new Set(config.pages.map(p=>experiencePage(config.siteType,p.family)))],site:checkout.repo,includePending:true,includeCreative:true,includeRetired:true,includeVisualSpecs:true,siteType:config.siteType,limit:100});
      const selected=selectTaskExperience(lessons,config);
      const opened=await openTask({data,id,repo:options.repo,ref:options.ref,localSource:options.source,config,lessons:selected,teamCreative:lessons.creative||[],teamRetired:lessons.creativeRetired||[],experienceMeta:{source:lessons.creativeSource || lessons.source || 'unknown',truncated:lessons.truncated===true,...(lessons.warning?{warning:lessons.warning}:{})}});
      if(options.source){const {bindPulledSource}=await import('../lib/library-client.mjs');await bindPulledSource(data,id,options.source);}
      if (action === 'open') return {id,step:'registered',experience:opened.experienceMeta?.source || 'unknown',experienceTruncated:opened.experienceMeta?.truncated===true,lessons:opened.lessons,creative:opened.creative};
      if(config.workflow==='adjustment')return adjustmentPreview({scope:config.adjustment});
      if(opened.adjustment)await resumeAcceptance(data,id);
      await prepare(data,id); await audit({data,id}); return status(data,id);
    }
    if (action === 'cycle') {
      const task=await loadTask(data,id);
      if(options.mode!=='acceptance' && (options.mode==='adjustment'||task.adjustment||task.pendingAdjustment||task.config.workflow==='adjustment'))return adjustmentPreview(payload);
      if(options.mode==='acceptance')await resumeAcceptance(data,id);
      await prepare(data,id); await audit({data,id}); return status(data,id);
    }
    if (action === 'status') return status(data,id,options.detail);
    if (action === 'adjust') return adjustmentPreview(payload);
    if (action === 'repair') {
      const task=await loadTask(data,id);
      if(options.mode==='adjustment'||task.adjustment||task.pendingAdjustment||task.config.workflow==='adjustment'||task.presented)
        return adjustmentPreview(payload);
      // Fixes discovered during initial acceptance must still complete the full review.
      await repair({...payload,data,id}); await audit({data,id}); return status(data,id);
    }
    if (action === 'recheck') {
      if(!(await loadTask(data,id)).adjustment)throw Error('Use adjust to locate the designer change before scoped recheck');
      await audit({data,id}); return status(data,id);
    }
    if (action === 'observe') { await recordObservations({...payload,data,id}); return status(data,id); }
    if (action === 'coverage') { await confirmCoverage({...payload,data,id}); return status(data,id); }
    if (action === 'feedback') {
      const updated=await feedback({...payload,data,id});
      const points=updated.feedback.at(-1)?.creativePoints||[];
      const visualLearning=points.some(p=>p.kind==='positive-reference'&&!p.visualSpec)?'pending-agent-inspection':points.some(p=>p.visualSpec)?'recorded':'not-applicable';
      const delivery=await scheduleFeedbackDelivery({data,id,feedbackId:updated.feedback.at(-1).id,url:options['experience-url'] || process.env.DA_EXPERIENCE_URL,token:process.env.DA_EXPERIENCE_TOKEN});
      return {...await status(data,id),visualLearning,experienceSync:delivery.status,experience:delivery,...(payload.decision==='note'?{creativeFeedback:'saved-local'}:{})};
    }
    if (action === 'handoff') { await handoff(data,id); return {task:await status(data,id),preview:await ensurePreview(data,id)}; }
    if (action === 'preview') return ensurePreview(data,id);
    if (action === 'stop-preview') { await stopPreview(data,id); return {id,stopped:true}; }
    if (action === 'learn') return learnTask({...payload,data,id,client});
    throw Error('Unknown workbench command');
  } finally { await client.close(); }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(JSON.stringify(await workbench(process.argv.slice(2)),null,2)); }
  catch (error) { console.error(error.message); process.exitCode=1; }
}
